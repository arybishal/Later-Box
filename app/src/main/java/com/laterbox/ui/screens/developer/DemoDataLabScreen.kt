@Composable
private fun RemovalSection(
    counts: com.laterbox.data.demo.DemoDatabaseCounts,
    isOperating: Boolean,
    onRemoveGeneral: () -> Unit,
    onRemoveRichNotes: () -> Unit,
    onRemoveStress: () -> Unit,
    onRemoveAll: () -> Unit
) {
    val extended = LaterBoxThemeTokens.extended
    Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
        Text(
            text = "Remove Synthetic Demo Records",
            style = MaterialTheme.typography.titleMedium,
            fontWeight = FontWeight.Bold,
            color = extended.primaryBlack
        )

        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(10.dp)
        ) {
            OutlinedButton(
                onClick = onRemoveGeneral,
                enabled = !isOperating && counts.generalDemoItems > 0,
                shape = RoundedCornerShape(12.dp),
                colors = ButtonDefaults.outlinedButtonColors(contentColor = extended.secondaryText),
                border = ButtonDefaults.outlinedButtonBorder.copy(brush = androidx.compose.ui.graphics.SolidColor(extended.border)),
                modifier = Modifier.weight(1f).height(44.dp)
            ) {
                Text("Clear General", fontSize = 12.5.sp)
            }

            OutlinedButton(
                onClick = onRemoveRichNotes,
                enabled = !isOperating && counts.richNotesDemoItems > 0,
                shape = RoundedCornerShape(12.dp),
                colors = ButtonDefaults.outlinedButtonColors(contentColor = extended.secondaryText),
                border = ButtonDefaults.outlinedButtonBorder.copy(brush = androidx.compose.ui.graphics.SolidColor(extended.border)),
                modifier = Modifier.weight(1f).height(44.dp)
            ) {
                Text("Clear Notes", fontSize = 12.5.sp)
            }

            if (counts.stressDemoItems > 0) {
                OutlinedButton(
                    onClick = onRemoveStress,
                    enabled = !isOperating,
                    shape = RoundedCornerShape(12.dp),
                    colors = ButtonDefaults.outlinedButtonColors(contentColor = extended.secondaryText),
                    border = ButtonDefaults.outlinedButtonBorder.copy(brush = androidx.compose.ui.graphics.SolidColor(extended.border)),
                    modifier = Modifier.weight(1f).height(44.dp)
                ) {
                    Text("Clear Stress", fontSize = 12.5.sp)
                }
            }
        }

        // Remove All Demo Data Button
        Button(
            onClick = onRemoveAll,
            enabled = !isOperating && counts.totalDemoItems > 0,
            colors = ButtonDefaults.buttonColors(
                containerColor = MaterialTheme.colorScheme.error.copy(alpha = 0.12f),
                contentColor = MaterialTheme.colorScheme.error
            ),
            shape = RoundedCornerShape(12.dp),
            modifier = Modifier.fillMaxWidth().height(48.dp)
        ) {
            Icon(imageVector = Icons.Default.DeleteOutline, contentDescription = null, modifier = Modifier.size(18.dp))
            Spacer(modifier = Modifier.width(8.dp))
            Text(
                text = "Remove All Demo Records (${counts.totalDemoItems})",
                fontWeight = FontWeight.Bold,
                fontSize = 13.5.sp
            )
        }
    }
}
