@Composable
fun DemoDataLabScreen(
    onBack: () -> Unit,
    modifier: Modifier = Modifier,
    viewModel: DemoDataLabViewModel = viewModel()
) {
    val uiState by viewModel.uiState.collectAsState()
    val extended = LaterBoxThemeTokens.extended
    val snackbarHostState = remember { SnackbarHostState() }

    LaunchedEffect(uiState.feedbackMessage) {
        uiState.feedbackMessage?.let { msg ->
            snackbarHostState.showSnackbar(msg)
            viewModel.clearFeedbackMessage()
        }
    }

    Scaffold(
        topBar = {
            DemoLabTopBar(
                title = "Demo Data Lab",
                subtitle = "Synthetic Testing & Benchmark Suite",
                onBack = onBack
            )
        },
        snackbarHost = { SnackbarHost(snackbarHostState) },
        containerColor = extended.background,
        modifier = modifier
    ) { paddingValues ->
        LazyColumn(
            modifier = Modifier
                .fillMaxSize()
                .padding(paddingValues),
            contentPadding = PaddingValues(horizontal = 20.dp, vertical = 12.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            // 1. Information Notice Card
            item {
                InfoNoticeCard(
                    message = "All records generated by the Demo Data Lab are synthetic fixtures designed to exercise Later Box search, rich document editing, playlists, filters, AI states, reminders, and backup/restore. Real user content is strictly isolated."
                )
            }

            // 2. Active Operation Progress (if running)
            if (uiState.isOperating) {
                item {
                    ProgressFeedbackCard(
                        progress = uiState.operationProgress,
                        status = uiState.operationStatus
                    )
                }
            }

            // 3. Database Status & Counts
            item {
                DatabaseSummaryCard(
                    counts = uiState.counts,
                    lastGenerated = uiState.lastGeneratedDate,
                    lastType = uiState.lastDatasetType,
                    integrity = uiState.integrity
                )
            }

            // 4. Deterministic Seed Setting
            item {
                SeedConfigurationCard(
                    useFixedSeed = uiState.useFixedSeed,
                    onToggle = { viewModel.setUseFixedSeed(it) }
                )
            }

            // 5. Standard Dataset Generation Controls
            item {
                GenerationSection(
                    isOperating = uiState.isOperating,
                    onGenerateComplete = { viewModel.requestGenerateComplete() },
                    onGenerateGeneral = { viewModel.requestGenerateGeneral() },
                    onGenerateRichNotes = { viewModel.requestGenerateRichNotes() },
                    onGenerateStress = { viewModel.requestGenerateStress(it) }
                )
            }

            // 6. Dataset Removal Controls
            item {
                RemovalSection(
                    counts = uiState.counts,
                    isOperating = uiState.isOperating,
                    onRemoveGeneral = { viewModel.requestRemoveGeneral() },
                    onRemoveRichNotes = { viewModel.requestRemoveRichNotes() },
                    onRemoveStress = { viewModel.requestRemoveStress() },
                    onRemoveAll = { viewModel.requestRemoveAll() }
                )
            }

            item {
                Spacer(modifier = Modifier.height(24.dp))
            }
        }
    }

    // Confirmation Dialogs
    uiState.pendingConfirmation?.let { conf ->
        when (conf) {
            is PendingConfirmation.Generate -> {
                GlassAlertDialog(
                    onDismissRequest = { viewModel.dismissConfirmation() },
                    title = {
                        Text(
                            text = conf.title,
                            fontWeight = FontWeight.Bold,
                            color = extended.primaryBlack
                        )
                    },
                    text = {
                        Text(
                            text = conf.description,
                            style = MaterialTheme.typography.bodyMedium,
                            color = extended.secondaryText
                        )
                    },
                    confirmButton = {
                        Button(
                            onClick = {
                                viewModel.dismissConfirmation()
                                conf.action()
                            },
                            colors = ButtonDefaults.buttonColors(
                                containerColor = extended.interactiveAccent,
                                contentColor = Color.White
                            ),
                            shape = RoundedCornerShape(10.dp)
                        ) {
                            Text("Generate ${conf.targetCount} Records")
                        }
                    },
                    dismissButton = {
                        TextButton(onClick = { viewModel.dismissConfirmation() }) {
                            Text("Cancel", color = extended.secondaryText)
                        }
                    },
                    shape = RoundedCornerShape(26.dp)
                )
            }
            is PendingConfirmation.Remove -> {
                GlassAlertDialog(
                    onDismissRequest = { viewModel.dismissConfirmation() },
                    title = {
                        Text(
                            text = conf.title,
                            fontWeight = FontWeight.Bold,
                            color = extended.primaryBlack
                        )
                    },
                    text = {
                        Text(
                            text = conf.description,
                            style = MaterialTheme.typography.bodyMedium,
                            color = extended.secondaryText
                        )
                    },
                    confirmButton = {
                        Button(
                            onClick = {
                                viewModel.dismissConfirmation()
                                conf.action()
                            },
                            colors = ButtonDefaults.buttonColors(
                                containerColor = MaterialTheme.colorScheme.error,
                                contentColor = Color.White
                            ),
                            shape = RoundedCornerShape(10.dp)
                        ) {
                            Text("Delete ${conf.countToRemove} Records")
                        }
                    },
                    dismissButton = {
                        TextButton(onClick = { viewModel.dismissConfirmation() }) {
                            Text("Cancel", color = extended.secondaryText)
                        }
                    },
                    shape = RoundedCornerShape(26.dp)
                )
            }
        }
    }
}

