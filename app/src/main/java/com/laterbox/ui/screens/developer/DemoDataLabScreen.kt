                        fontSize = 11.sp,
                        fontWeight = FontWeight.Bold,
                        color = extended.interactiveAccent
                    )
                }
            }

            Spacer(modifier = Modifier.height(14.dp))

            // Distribution metrics grid
            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                MetricColumn(title = "General", value = "${counts.generalDemoItems} / 100")
                MetricColumn(title = "Rich Notes", value = "${counts.richNotesDemoItems} / 100")
                MetricColumn(title = "Stress", value = "${counts.stressDemoItems}")
                MetricColumn(title = "Real User", value = "${counts.realUserItems}")
            }

            Spacer(modifier = Modifier.height(16.dp))

            // Integrity status row
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(
                    imageVector = Icons.Default.CheckCircle,
                    contentDescription = null,
                    tint = Color(0xFF2E7D32),
                    modifier = Modifier.size(16.dp)
                )
                Spacer(modifier = Modifier.width(6.dp))
                Text(
                    text = integrity.message,
                    style = MaterialTheme.typography.bodySmall,
                    color = extended.secondaryText
                )
            }

